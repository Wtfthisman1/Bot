package Bot.insight;

/**
 * Языковая модель, которой отдают текст расшифровки.
 *
 * <p>Интерфейс, а не сразу клиент к Ollama: обработка — это последовательность
 * запросов с разными подсказками, и проверять её сборку на живой модели значило
 * бы гонять видеокарту ради того, что решается подставной реализацией. Заодно
 * остаётся выход, если модель однажды переедет на другую машину.</p>
 */
public interface LanguageModel {

    /** Готова ли модель отвечать: служба поднята, веса на месте. */
    boolean available();

    /** Название модели — попадает в строку результата рядом с текстом. */
    String name();

    /**
     * Один вопрос — один ответ.
     *
     * @param instruction кто она и что делает: правила, одинаковые для всех
     *                    кусков одной обработки
     * @param prompt      сам текст с вопросом
     */
    String ask(String instruction, String prompt);

    /**
     * Выгрузить веса из видеопамяти.
     *
     * <p>Вызывается после обработки, а не после каждого вопроса: расшифровка
     * и модель делят одни 8 ГБ, и оставленная в памяти модель означала бы, что
     * следующий Whisper упрётся в нехватку памяти. Внутри одной обработки веса,
     * наоборот, должны остаться — иначе каждый кусок оплачивал бы загрузку
     * заново.</p>
     */
    void unload();
}
