package Bot.insight;

/**
 * Что человек попросил сделать с расшифровкой.
 *
 * <p>Две кнопки — два разных вопроса к одному тексту. Выжимка отвечает «о чём
 * это вообще было», разбор по теме — «что здесь говорили про Альцгеймера».
 * Первое читают вместо записи, второе — чтобы найти место, куда перемотать,
 * когда одного совпадения по слову мало: тему обсуждают, ни разу её не назвав.</p>
 */
public enum InsightKind {

    /** Краткое изложение; насколько краткое — задаёт доля от исходного текста. */
    SUMMARY("Выжимка"),

    /** Всё, что относится к заданной теме, собранное в связный рассказ. */
    TOPIC("Разбор по теме");

    private final String title;

    InsightKind(String title) {
        this.title = title;
    }

    /** Как это называется на странице. */
    public String title() {
        return title;
    }
}
