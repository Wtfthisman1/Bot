package Bot.config;

/**
 * Профили Spring: какая половина приложения поднята в этом процессе.
 *
 * <p>Ответственность: назвать две стороны, на которые разъезжается бот.
 * {@link #HOME} — база, очередь, файлы, yt-dlp и Whisper; всё это остаётся на
 * домашней машине с видеокартой и диском. {@link #BOT} — приём запросов:
 * long polling Telegram, а дальше и сайт; ему хватает VPS с 960 МБ памяти,
 * потому что ни базы, ни файлов у него нет.</p>
 *
 * <p>Оба профиля вместе — это привычный запуск на одной машине, и он остаётся
 * значением по умолчанию ({@code spring.profiles.default}). Иначе разделение
 * сломало бы каждую существующую установку в момент обновления.</p>
 */
public final class Profiles {

    /** Дом: очередь, база, файлы и тяжёлая работа. */
    public static final String HOME = "home";

    /** Приём запросов: Telegram, дальше сайт. */
    public static final String BOT = "bot";

    private Profiles() {
    }
}
