package Bot.processing;

/**
 * Что происходит с задачей прямо сейчас.
 *
 * <p>Отдельно от {@link ProcessingJob.Stage}: этап отвечает на вопрос «что
 * делать» (скачать или расшифровать), состояние — «на каком мы шаге». Одна
 * колонка на оба смысла мешала бы выбирать очередь: «скачать» и «в работе» —
 * не альтернативы, а разные измерения.</p>
 */
public enum JobState {
    /** Ждёт свободного воркера. */
    QUEUED,
    /** Взята воркером. Если бот перезапустится — вернётся в очередь. */
    RUNNING,
    /** Отработала: файл скачан или расшифровка отправлена. */
    DONE,
    /** Сорвалась; причина — в колонке error. */
    FAILED,
    /**
     * Остановлена человеком.
     *
     * <p>Отдельно от {@link #FAILED}: в истории «не получилось» и «передумал» —
     * разные вещи, а по журналу настоящие поломки иначе тонули бы в отменах.
     * Квоту, как и поломка, не тратит.</p>
     */
    CANCELLED
}
