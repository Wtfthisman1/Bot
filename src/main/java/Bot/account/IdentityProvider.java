package Bot.account;

/**
 * Чем человек подтверждает, что это он.
 *
 * <p>Здесь только внешние провайдеры. Почта с паролем и телефон — колонки
 * самого аккаунта: они принадлежат нам, и отдельная запись о них ничего
 * не добавила бы.</p>
 */
public enum IdentityProvider {

    /** OpenID Connect, {@code sub} из id-токена. */
    GOOGLE,

    /**
     * Виджет входа Telegram, поле {@code id}.
     *
     * <p>Для приватного чата это тот же номер, что и chat id, с которым бот
     * уже работает. Совпадение не случайно: благодаря ему вход на сайт через
     * Telegram попадает в аккаунт, где уже лежат задачи из переписки.</p>
     */
    TELEGRAM
}
