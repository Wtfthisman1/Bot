package Bot.home;

/**
 * Дом не отвечает.
 *
 * <p>Отдельный тип, потому что для пользователя это не поломка, а состояние:
 * домашняя машина спит или перезагружается. Ответ должен быть человеческим
 * («сейчас недоступно, попробуйте позже»), а не «внутренняя ошибка», и уж
 * точно не молчанием — задачу-то не приняли.</p>
 */
public class HomeUnavailableException extends RuntimeException {

    /**
     * Один текст на все случаи: пользователю безразлично, на каком шаге не
     * дозвонились до дома, — важно, что задача не принята и стоит зайти позже.
     */
    public static final String USER_MESSAGE =
            "🌙 Сейчас не могу принять задачу: рабочая машина недоступна. "
                    + "Она включается не круглосуточно — попробуйте позже.";

    public HomeUnavailableException(String message, Throwable cause) {
        super(message, cause);
    }
}
