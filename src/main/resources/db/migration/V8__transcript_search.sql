-- Поиск по расшифровкам.
--
-- Расшифровка часовой записи — это сотни реплик, и «где-то он говорил про
-- гиппокамп» без поиска означает перечитать всё. Ищем по сегментам, а не по
-- задаче целиком: найти нужно не запись, а место в ней, куда перемотать.
--
-- Колонка вычисляемая (generated always as ... stored), а не заполняемая
-- триггером или приложением: правки текста идут из редактора обычным update,
-- и любое место, где забыли обновить индексную колонку, дало бы поиск по
-- старому тексту.
--
-- Конфигурация russian отсекает русские стоп-слова и приводит слова к основе
-- («гиппокампе» находится по «гиппокамп»). Латиница проходит через неё без
-- стемминга — английские слова ищутся по точной форме, и это лучше, чем никак.

alter table transcript_segments
    add column search tsvector generated always as (to_tsvector('russian', text)) stored;

create index transcript_segments_search_idx on transcript_segments using gin (search);
