-- Вход на сайт через бота, без номера телефона.
--
-- Виджет Telegram спрашивает номер и присылает подтверждение в приложение —
-- шаг лишний для того, у кого бот уже открыт. Здесь наоборот: сайт выдаёт
-- одноразовый код, человек открывает бота по ссылке и подтверждает вход
-- кнопкой, а страница входа ждёт этого подтверждения.
--
-- Подтверждение обязательно кнопкой, а не самим фактом /start: ссылку с чужим
-- кодом можно прислать постороннему, и тогда нажатие «Запустить» пустило бы
-- отправителя в его аккаунт. Кнопка называет домен явно и требует осознанного
-- согласия.

create table bot_login_codes (
    code         text        primary key,

    created_at   timestamptz not null default now(),
    -- Живёт минуты: код лежит в открытой вкладке и в адресе ссылки
    expires_at   timestamptz not null,

    -- Заполняется, когда человек подтвердил вход в боте
    chat_id      bigint,
    display_name text,
    confirmed_at timestamptz,

    -- Заполняется, когда браузер забрал подтверждение и вошёл: второй раз
    -- по тому же коду войти нельзя
    used_at      timestamptz
);

-- Просроченные коды чистятся по расписанию — запрос идёт по этой колонке
create index bot_login_codes_expires_idx on bot_login_codes (expires_at);
