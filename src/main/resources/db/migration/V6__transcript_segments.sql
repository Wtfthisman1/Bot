-- Расшифровка перестаёт быть плоским текстом.
--
-- До сих пор результатом задачи был файл .txt: показать его можно, а вот
-- перемотать запись к нужной фразе, поправить слово или сказать, кто говорит, —
-- нельзя. Всё это требует одного и того же: расшифровки, разложенной на
-- сегменты со временем.
--
-- Таблица, а не JSONB в jobs: по сегментам будет полнотекстовый поиск, а внутри
-- JSONB он получается неповоротливым и требует своих индексов на каждое поле.
--
-- Сегменты живут ровно столько, сколько задача: on delete cascade избавляет от
-- отдельной чистки, а чистильщик файлов их не касается — текст занимает
-- килобайты против гигабайтов видео.

create table transcript_segments (
    id        bigserial   primary key,
    job_id    uuid        not null references jobs (id) on delete cascade,

    -- Порядок в расшифровке. Сортировать по времени нельзя: сегменты
    -- диаризации могут начинаться в одну и ту же миллисекунду
    ord       integer     not null,

    start_ms  integer     not null,
    end_ms    integer     not null,

    -- Метка говорящего от диаризации: SPEAKER_00, SPEAKER_01. NULL — значит,
    -- диаризацию не делали (старые расшифровки и записи с одним голосом)
    speaker   text,

    text      text        not null,

    -- Правил ли человек этот сегмент руками. Нужно, чтобы повторная обработка
    -- записи не затирала правки молча
    edited    boolean     not null default false,

    unique (job_id, ord)
);

-- Кабинет всегда читает сегменты одной задачи и всегда по порядку
create index transcript_segments_job_idx on transcript_segments (job_id, ord);
