-- Вход на сайт начинает бот, а не браузер.
--
-- Раньше код входа рождался на странице, а подтверждали его в чате: человек
-- получал ссылку t.me/...?start=login_<код> и выбирал в боте одно из трёх
-- чисел. Слабое место было не в числе, а в направлении. Начать вход мог кто
-- угодно, а подтверждать шли к чужому человеку: достаточно было прислать ему
-- ссылку под благовидным предлогом, и с вероятностью один к трём он угадывал
-- нужное число — а входил тот, кто ссылку прислал. Промах гасил код, но новую
-- попытку никто не запрещал.
--
-- Теперь ссылку выдаёт бот тому, кто её попросил, и ведёт она сразу на сайт.
-- Токен рождается из чата человека и приходит только в этот чат, поэтому
-- прислать постороннему нечего: ссылка на чужой аккаунт ниоткуда не берётся.
-- Числа сверки, кнопки «Это я» и полезная нагрузка login_ больше не нужны.
--
-- Старая таблица удаляется целиком: коды жили пять минут, переносить нечего.

drop table if exists bot_login_codes;

create table bot_login_links (
    token        text        primary key,

    -- Кому выдана. Не заполняется потом, как раньше, а известна сразу: ссылку
    -- просит сам чат, и в этом вся защита
    chat_id      bigint      not null,
    display_name text,

    created_at   timestamptz not null default now(),
    -- Живёт минуты: ссылка лежит в переписке, и долгая жизнь ей ни к чему
    expires_at   timestamptz not null,

    -- Заполняется, когда по ссылке вошли: второй раз она не сработает
    used_at      timestamptz
);

-- Просроченные ссылки чистятся по расписанию — запрос идёт по этой колонке
create index bot_login_links_expires_idx on bot_login_links (expires_at);
