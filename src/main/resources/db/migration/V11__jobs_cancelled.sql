-- Отменённая задача — не сломавшаяся.

-- Раньше состояний было четыре, и остановленную вручную работу пришлось бы
-- записывать в FAILED. Это враньё в двух местах сразу: в истории человек видел
-- бы «не получилось» там, где он сам передумал, а разбор настоящих поломок по
-- журналу превращался бы в отсеивание чужого.
--
-- Квоту отмена не тратит — как и поломка: списывать месячный лимит за работу,
-- которую человек остановил через минуту после запуска, не за что.
alter table jobs drop constraint if exists jobs_state_check;

alter table jobs add constraint jobs_state_check
    check (state in ('QUEUED', 'RUNNING', 'DONE', 'FAILED', 'CANCELLED'));
