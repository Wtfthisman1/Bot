-- Сверяемое число для входа через бота.
--
-- Кнопка «Это я» подтверждала вход, ничего не спрашивая о том, что человек
-- видит на экране. Этого мало: код можно прислать постороннему под любым
-- предлогом («подтвердите, что аккаунт ваш»), и он нажмёт кнопку, не открывая
-- никакой страницы, — а войдёт тот, кто прислал ссылку. Предупреждения в
-- тексте от этого не спасают: их читают редко, а кнопку жмут всегда.
--
-- Теперь страница показывает двузначное число, а бот предлагает выбрать его
-- из трёх. Тому, кто ничего не открывал, сверять не с чем — и совпадение
-- становится не вопросом внимательности, а вопросом наличия той самой вкладки.

alter table bot_login_codes
    add column check_number integer;
