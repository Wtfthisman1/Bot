-- Имена говорящих, данные человеком.
--
-- Диаризация различает голоса, но не знает, как их зовут: она выдаёт
-- SPEAKER_00 и SPEAKER_01. Показывать это в расшифровке бессмысленно, поэтому
-- в кабинете голоса переименовываются — «Ведущий», «Гость», — а метка остаётся
-- ключом, по которому имя подставляется в каждый сегмент.
--
-- Отдельная таблица, а не колонка в сегменте: имя одно на весь разговор, и
-- переименование не должно переписывать сотни строк.

create table transcript_speakers (
    job_id  uuid not null references jobs (id) on delete cascade,

    -- Метка от диаризации: SPEAKER_00 и подобные
    label   text not null,

    -- Как этот голос зовут по мнению человека
    name    text not null,

    primary key (job_id, label)
);
